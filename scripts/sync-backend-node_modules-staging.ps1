# Copia backend/node_modules completo Desktop -> share (PC-N8N). Ejecutar en PC de desarrollo.
param(
  [string]$Source = 'C:\Users\Admin\Desktop\intranet1\backend\node_modules',
  [string]$Target = 'Z:\Bacarnet\backend\node_modules'
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path $Source)) {
  throw "No existe $Source - corre npm install en backend primero."
}
if (-not (Test-Path 'Z:\Bacarnet')) {
  throw 'Monta Z:\Bacarnet antes de sincronizar.'
}

Write-Host 'Robocopy node_modules (puede tardar varios minutos)...'
robocopy $Source $Target /E /R:2 /W:2 /MT:8 /NFL /NDL /NJH /NJS
if ($LASTEXITCODE -ge 8) { exit $LASTEXITCODE }
Write-Host 'OK. En PC-N8N: pm2 restart bacarnet-emulators --update-env'
Write-Host 'Probar en PC-N8N: curl http://127.0.0.1:5000/api/health'
