import { TEXTO_PRACTICA, type Guia, type PasoRecorrido } from '../pasosRecorrido'

const RUTA = '/finanzas/hoy'
const VENTANA_PAGAR = 'hoy-pagar-ventana'

const SIN_PAGOS =
  'Hoy no hay pagos para practicar. Cargá un compromiso en Agenda y, el día que venza, va a aparecer acá con el botón «Pagar». Te cuento cómo sigue.'
const SIN_COBROS =
  'Hoy no hay cobros esperados para practicar. Cargalos en Agenda › Cobros esperados y, el día que esperás la plata, aparecen acá. Te cuento cómo sigue.'

function tocarPagar(): PasoRecorrido {
  return {
    id: 'pagar',
    ruta: RUTA,
    selector: 'hoy-pagar',
    tipo: 'tocar',
    espera: VENTANA_PAGAR,
    titulo: 'Abrí el pago',
    texto: 'Tocá «Pagar» en el compromiso que querés pagar.',
    sinDatos: SIN_PAGOS,
  }
}

function tocarMenuPago(espera: string, texto: string): PasoRecorrido {
  return {
    id: 'menu',
    ruta: RUTA,
    selector: 'hoy-pago-menu',
    tipo: 'tocar',
    espera,
    titulo: 'Abrí el menú del pago',
    texto,
    sinDatos: SIN_PAGOS,
  }
}

